"""
Experiment 12: controlled edge/torn-off preservation stress test.

Purpose
-------
Previous experiments reconstructed synthetically removed ommatidia from
internal regions where surrounding lattice information remained available.

This experiment asks whether the SAME interior Voronoi-hole detector can be
applied to a different preservation mode: consecutive loss from the outer
boundary of the eye.

Important interpretation
------------------------
This is a stress test of the existing interior interpolation method, not a
new edge-reconstruction algorithm.

Controlled cases are generated by:
1. mapping the intact ODA CT ommatidial centers to the fitted spherical surface;
2. identifying the outer convex-hull sequence;
3. removing 1–5 consecutive hull ommatidia;
4. refitting the sphere from surviving centers;
5. running the current blind interior-hole detector unchanged;
6. asking where the detector ranks a hypothesis nearest the true torn region.

A poor result means the existing method should NOT be claimed for boundary loss.
That is expected because boundary loss is an extrapolation problem and the
current detector explicitly searches within the surviving convex hull.

Run from the ODA repository root:
    ./oda_env/bin/python research/missing_lens/12_edge_torn_stress_test.py
"""

from pathlib import Path

import numpy as np
import pandas as pd
from scipy.spatial import Voronoi, cKDTree, ConvexHull, Delaunay
from sklearn.cluster import DBSCAN


ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / "tests/d_mauritiana_ct_stack/ommatidial_data.csv"
OUTDIR = ROOT / "research/missing_lens/results"
OUTDIR.mkdir(parents=True, exist_ok=True)

MERGE_FACTOR = 0.40
ANGLE_GAP_LIMIT = 150


def fit_sphere_map(observed_xyz, truth_xyz=None):
    A = np.column_stack([2 * observed_xyz, np.ones(len(observed_xyz))])
    b = np.sum(observed_xyz ** 2, axis=1)

    solution, *_ = np.linalg.lstsq(A, b, rcond=None)
    center = solution[:3]

    vectors = observed_xyz - center
    radii = np.linalg.norm(vectors, axis=1)

    theta = np.arccos(
        np.clip(vectors[:, 2] / radii, -1, 1)
    )
    phi = np.arctan2(vectors[:, 1], vectors[:, 0])

    phi_scale = float(np.sin(np.median(theta)))

    points = np.column_stack([
        phi * phi_scale,
        theta,
    ])

    truth_points = None

    if truth_xyz is not None:
        truth_vectors = np.atleast_2d(truth_xyz) - center
        truth_radii = np.linalg.norm(truth_vectors, axis=1)

        truth_theta = np.arccos(
            np.clip(
                truth_vectors[:, 2] / truth_radii,
                -1,
                1,
            )
        )
        truth_phi = np.arctan2(
            truth_vectors[:, 1],
            truth_vectors[:, 0],
        )

        truth_points = np.column_stack([
            truth_phi * phi_scale,
            truth_theta,
        ])

    return points, truth_points


def physical_holes(points):
    voronoi = Voronoi(points)
    candidates = voronoi.vertices

    hull = ConvexHull(points)
    hull_test = Delaunay(points[hull.vertices])

    # The current interior detector deliberately searches only within the
    # surviving convex hull. This becomes a critical limitation for torn edges.
    candidates = candidates[
        hull_test.find_simplex(candidates) >= 0
    ]

    tree = cKDTree(points)

    nearest_distances, _ = tree.query(points, k=2)
    nearest_other = nearest_distances[:, 1]

    distances, indices = tree.query(candidates, k=6)

    local_spacing = np.median(
        nearest_other[indices],
        axis=1,
    )
    gap_score = (
        distances[:, 0]
        / local_spacing
    )

    nearby = points[indices]
    vectors = (
        nearby
        - candidates[:, None, :]
    )

    angles = np.sort(
        np.arctan2(
            vectors[:, :, 1],
            vectors[:, :, 0],
        ),
        axis=1,
    )

    circular_gaps = np.diff(
        np.concatenate(
            [
                angles,
                angles[:, :1] + 2 * np.pi,
            ],
            axis=1,
        ),
        axis=1,
    )

    max_angle_gap = np.degrees(
        circular_gaps.max(axis=1)
    )

    keep = (
        max_angle_gap
        <= ANGLE_GAP_LIMIT
    )

    candidates = candidates[keep]
    local_spacing = local_spacing[keep]
    gap_score = gap_score[keep]

    merge_radius = (
        MERGE_FACTOR
        * float(np.median(local_spacing))
    )

    cluster_ids = DBSCAN(
        eps=merge_radius,
        min_samples=1,
    ).fit_predict(candidates)

    groups = []

    for cluster_id in np.unique(cluster_ids):
        use = (
            cluster_ids
            == cluster_id
        )

        center = np.average(
            candidates[use],
            axis=0,
            weights=gap_score[use],
        )

        groups.append({
            "center": center,
            "score": float(
                gap_score[use].max()
            ),
            "n_vertices": int(use.sum()),
        })

    groups.sort(
        key=lambda group: group["score"],
        reverse=True,
    )

    return groups


df = pd.read_csv(DATA)

# The intact hull is used ONLY to define controlled edge-loss test cases.
full_points, _ = fit_sphere_map(
    df[["x", "y", "z"]].to_numpy(float)
)

full_hull = ConvexHull(full_points)

hull_labels = (
    df.iloc[full_hull.vertices]["label"]
    .to_numpy(dtype=int)
)

records = []

for hidden_count in (1, 2, 3, 4, 5):

    for start in range(len(hull_labels)):

        hidden = [
            int(
                hull_labels[
                    (start + offset)
                    % len(hull_labels)
                ]
            )
            for offset
            in range(hidden_count)
        ]

        truth_df = df[
            df["label"].isin(hidden)
        ]

        observed_df = df[
            ~df["label"].isin(hidden)
        ]

        observed_points, truth_points = fit_sphere_map(
            observed_df[
                ["x", "y", "z"]
            ].to_numpy(float),

            truth_df[
                ["x", "y", "z"]
            ].to_numpy(float),
        )

        groups = physical_holes(
            observed_points
        )

        centers = np.asarray([
            group["center"]
            for group in groups
        ])

        scores = np.asarray([
            group["score"]
            for group in groups
        ])

        truth_center = (
            truth_points.mean(axis=0)
        )

        tree = cKDTree(
            observed_points
        )

        _, local_indices = tree.query(
            truth_center,
            k=12,
        )

        local_points = observed_points[
            np.atleast_1d(local_indices)
        ]

        local_nn, _ = cKDTree(
            local_points
        ).query(
            local_points,
            k=2,
        )

        spacing = float(
            np.median(
                local_nn[:, 1]
            )
        )

        distance_to_truth = (
            np.linalg.norm(
                centers
                - truth_center,
                axis=1,
            )
            / spacing
        )

        nearest_index = int(
            np.argmin(
                distance_to_truth
            )
        )

        records.append({
            "hidden_count": hidden_count,
            "start": start,
            "labels": " ".join(
                map(str, hidden)
            ),
            "nearest_truth_candidate_rank":
                nearest_index + 1,
            "nearest_truth_candidate_error":
                float(
                    distance_to_truth[
                        nearest_index
                    ]
                ),
            "top1_error":
                float(
                    np.linalg.norm(
                        centers[0]
                        - truth_center
                    )
                    / spacing
                ),
            "top1_score":
                float(scores[0]),
            "truth_nearest_score":
                float(
                    scores[
                        nearest_index
                    ]
                ),
        })


results = pd.DataFrame(records)

results.to_csv(
    OUTDIR
    / "12_edge_torn_stress_results.csv",
    index=False,
)


summary_rows = []

for hidden_count, subset in results.groupby(
    "hidden_count"
):

    summary_rows.append({
        "hidden_count":
            int(hidden_count),

        "n_cases":
            len(subset),

        "true_region_top1_pct":
            100
            * (
                subset[
                    "nearest_truth_candidate_rank"
                ] == 1
            ).mean(),

        "true_region_top5_pct":
            100
            * (
                subset[
                    "nearest_truth_candidate_rank"
                ] <= 5
            ).mean(),

        "median_true_region_rank":
            float(
                subset[
                    "nearest_truth_candidate_rank"
                ].median()
            ),

        "median_nearest_candidate_error_spacing":
            float(
                subset[
                    "nearest_truth_candidate_error"
                ].median()
            ),

        "median_top1_error_spacing":
            float(
                subset[
                    "top1_error"
                ].median()
            ),
    })


summary = pd.DataFrame(
    summary_rows
)

summary.to_csv(
    OUTDIR
    / "12_edge_torn_stress_summary_table.csv",
    index=False,
)


print(
    "Controlled outer-hull ommatidia:",
    len(hull_labels),
)

print(
    "\nEDGE/TORN-OFF STRESS TEST"
)

print(
    summary.to_string(
        index=False
    )
)

print(
    "\nInterpretation:"
)

print(
    "The current interior Voronoi-hole detector does not generalize "
    "to torn-edge loss."
)

print(
    "This is expected: the present method is an interpolation method "
    "inside the surviving convex hull, whereas edge loss requires "
    "boundary/lattice extrapolation."
)
